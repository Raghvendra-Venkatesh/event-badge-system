require('dotenv').config();

const db = require('./db');
const { DEFAULT_TIME_ZONE, isValidTimeZone } = require('./dateTime');

async function setupDatabase() {
  await db.query(`
    CREATE TABLE IF NOT EXISTS participants (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      badge_id    TEXT UNIQUE NOT NULL,
      name        TEXT,
      email       TEXT,
      phone       TEXT,
      type        TEXT DEFAULT 'delegate',
      company     TEXT,
      tnmc_no     TEXT,
      qr_base64   TEXT,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      archived_at TIMESTAMPTZ
    )
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS scans (
      id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      participant_id INTEGER REFERENCES participants(id) ON DELETE SET NULL,
      badge_id       TEXT NOT NULL,
      station        TEXT NOT NULL,
      result         TEXT NOT NULL,
      operator_id    TEXT,
      scanned_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      scan_day       DATE
    )
  `);

  await db.query(`
    CREATE TABLE IF NOT EXISTS settings (
      key   TEXT PRIMARY KEY,
      value TEXT
    )
  `);

  await db.query('ALTER TABLE participants ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ');
  await db.query('ALTER TABLE scans ADD COLUMN IF NOT EXISTS scan_day DATE');
  await db.query("INSERT INTO settings(key, value) VALUES('event_timezone', ?) ON CONFLICT(key) DO NOTHING", [
    process.env.EVENT_TIME_ZONE || DEFAULT_TIME_ZONE
  ]);
  await db.query("INSERT INTO settings(key, value) VALUES('event_name', 'My Event') ON CONFLICT(key) DO NOTHING");
  await db.query("INSERT INTO settings(key, value) VALUES('event_date', '') ON CONFLICT(key) DO NOTHING");

  const setting = await db.query("SELECT value FROM settings WHERE key = 'event_timezone'");
  const timeZone = setting.rows[0] && setting.rows[0].value;
  if (!isValidTimeZone(timeZone)) {
    throw new Error(`Invalid event_timezone setting: ${timeZone}`);
  }

  await db.query(
    `UPDATE scans
     SET scan_day = (scanned_at AT TIME ZONE ?)::date
     WHERE scan_day IS NULL`,
    [timeZone]
  );
  await db.query('ALTER TABLE scans ALTER COLUMN scan_day SET NOT NULL');
  await db.query('CREATE INDEX IF NOT EXISTS scans_participant_station_day_idx ON scans(participant_id, station, scan_day)');
  await db.query('CREATE INDEX IF NOT EXISTS scans_scanned_at_idx ON scans(scanned_at DESC)');
  await db.query('CREATE INDEX IF NOT EXISTS participants_active_name_idx ON participants(name) WHERE archived_at IS NULL');

  const badgeMax = await db.query(
    "SELECT COALESCE(MAX(CAST(SUBSTRING(badge_id FROM 5) AS INTEGER)), 0) AS max FROM participants WHERE badge_id ~ '^BDG-[0-9]+$'"
  );
  await db.query('CREATE SEQUENCE IF NOT EXISTS participant_badge_counter_seq START WITH 1');
  const sequence = await db.query("SELECT last_value, is_called FROM participant_badge_counter_seq");
  const maxBadge = Number(badgeMax.rows[0].max);
  if (maxBadge > 0 && (!sequence.rows[0].is_called || Number(sequence.rows[0].last_value) < maxBadge)) {
    await db.query("SELECT setval('participant_badge_counter_seq', ?, true)", [maxBadge]);
  }

}

if (require.main === module) {
  setupDatabase()
    .then(() => {
      console.log('PostgreSQL schema is ready.');
      return db.close();
    })
    .catch(async error => {
      console.error('Database setup failed:', error);
      await db.close();
      process.exitCode = 1;
    });
}

module.exports = setupDatabase;
